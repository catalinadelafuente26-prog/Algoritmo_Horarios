def importar():
    db.inicializar_db()
    profesores_bd = db.obtener_profesores()

    # Crear índice nombre → id para búsqueda rápida
    indice = {}
    for p in profesores_bd:
        nombre_normalizado = p["nombre"].strip().upper()
        indice[nombre_normalizado] = p["id"]

    cargadas = 0
    sin_match = []

    for nombre_hab, ramos in HABILITACIONES.items():
        nombre_norm = nombre_hab.strip().upper()
        prof_id = indice.get(nombre_norm)

        if not prof_id:
            # Buscar coincidencia parcial por apellido principal
            for nombre_bd, pid in indice.items():
                primer_apellido = nombre_norm.split()[1] if len(nombre_norm.split()) > 1 else ""
                if primer_apellido and primer_apellido in nombre_bd:
                    prof_id = pid
                    break

        if prof_id:
            for ramo in ramos:
                db.asignar_asignatura_profesor(prof_id, ramo)
                cargadas += 1
            print(f"  [OK] {nombre_hab} → {len(ramos)} ramo(s)")
        else:
            sin_match.append(nombre_hab)
            print(f"  [NO ENCONTRADO] {nombre_hab}")

    print(f"\nListo. {cargadas} habilitaciones cargadas.")
    if sin_match:
        print(f"Profesores sin match en BD ({len(sin_match)}):")
        for s in sin_match:
            print(f"  - {s}")

if __name__ == "__main__":
    importar()